import { Link } from "react-router-dom";
import { AlertTriangle, Bot, XCircle } from "lucide-react";
import { Badge } from "@/common/ui";
import { RUN_STATUS_LABELS, type Issue, type Run } from "../api/scheduling";
import { fixLink } from "../utils/links";
import "./scheduling.css";

export function RunStatusBadge({ run }: { run: Pick<Run, "status"> }) {
  const tone = run.status === "APPLIED" ? "success" : run.status === "DRAFT" ? "info" : "neutral";
  return (
    <Badge tone={tone} dot>
      {RUN_STATUS_LABELS[run.status]}
    </Badge>
  );
}

/* A run an AI agent asked for (through its tools) rather than a person on this page */
export function AgentBadge({ run }: { run: Pick<Run, "origin"> }) {
  if (run.origin !== "AGENT_TOOL") return null;
  return (
    <span title="Generated by an AI agent">
      <Badge tone="primary">
        <Bot size={12} style={{ marginRight: 3, verticalAlign: -1 }} />
        AI agent
      </Badge>
    </span>
  );
}

/* Problems, errors first, each with its fix page when there is an obvious one */
export function IssueList({ issues, links = true }: { issues: Issue[]; links?: boolean }) {
  const sorted = [...issues].sort((a, b) => (a.severity === b.severity ? 0 : a.severity === "ERROR" ? -1 : 1));
  return (
    <ul className="sch-issues">
      {sorted.map((issue, i) => {
        const fix = links ? fixLink(issue) : null;
        return (
          <li key={`${issue.code}-${i}`} className={issue.severity === "ERROR" ? "is-error" : "is-warning"}>
            {issue.severity === "ERROR" ? <XCircle aria-label="Problem" /> : <AlertTriangle aria-label="Warning" />}
            <span className="sch-issue-text">{issue.message}</span>
            {fix && (
              <Link className="sch-issue-fix" to={fix.to}>
                {fix.label}
              </Link>
            )}
          </li>
        );
      })}
    </ul>
  );
}

/* "the teacher is teaching another class · 12 periods": why a class or paper found no place, most common first */
export function Reasons({ reasons }: { reasons: { code: string; text: string; cells?: number; sittings?: number }[] }) {
  if (!reasons.length) return null;
  return (
    <ul className="sch-reasons">
      {reasons.map(r => {
        const n = r.cells ?? r.sittings ?? 0;
        const unit = r.cells !== undefined ? (n === 1 ? "period" : "periods") : n === 1 ? "sitting" : "sittings";
        return (
          <li key={r.code}>
            {r.text}
            <span className="muted">
              {" "}
              · {n} {unit}
            </span>
          </li>
        );
      })}
    </ul>
  );
}
